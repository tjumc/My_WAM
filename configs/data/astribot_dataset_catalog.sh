astribot_select_dataset_task() {
    local task_name="${1:?task name is required}"

    if [[ -z "${ASTRIBOT_DATASET_CATALOG[$task_name]+x}" ]]; then
        echo "ERROR: unknown Astribot dataset task: $task_name" >&2
        return 1
    fi

    mapfile -t WAM_DATASET_DIRS <<< "${ASTRIBOT_DATASET_CATALOG[$task_name]}"
}

astribot_list_dataset_tasks() {
    local task_name
    local -a task_dirs

    for task_name in "${ASTRIBOT_DATASET_TASKS[@]}"; do
        mapfile -t task_dirs <<< "${ASTRIBOT_DATASET_CATALOG[$task_name]}"
        printf '%-24s %3d\n' "$task_name" "${#task_dirs[@]}"
    done
}

if [[ "${BASH_SOURCE[0]}" == "$0" ]]; then
    astribot_list_dataset_tasks
fi